-- Usage:   psql -U postgres -d skillshub -f skillshub_seed.sql
-- Safe to re-run: it drops and recreates the Skills Hub tables first.

BEGIN;

DROP TABLE IF EXISTS person_project_assignment CASCADE;
DROP TABLE IF EXISTS project_skill_required   CASCADE;
DROP TABLE IF EXISTS person_skill             CASCADE;
DROP TABLE IF EXISTS projects                 CASCADE;
DROP TABLE IF EXISTS skill_proficiency_level  CASCADE;
DROP TABLE IF EXISTS skill                    CASCADE;
DROP TABLE IF EXISTS person                   CASCADE;
DROP TABLE IF EXISTS organization             CASCADE;

-- Schema

CREATE TABLE organization (
    organization_id            INTEGER      PRIMARY KEY,
    organization_name          VARCHAR(255) NOT NULL,
    manager_person_id          INTEGER                      -- FK added below
);

CREATE TABLE person (
    person_id                  INTEGER      PRIMARY KEY,
    person_name                VARCHAR(255) NOT NULL,
    manager_person_id          INTEGER,                     -- NULL means the top of the org chart
    member_of_organization_id  INTEGER      NOT NULL,
    is_admin                   BOOLEAN      NOT NULL DEFAULT FALSE
);

-- Circular references (person <-> organization, person -> person) are deferrable so the data can be loaded in a single transaction.
ALTER TABLE person
    ADD CONSTRAINT fk_person_manager
        FOREIGN KEY (manager_person_id) REFERENCES person (person_id)
        DEFERRABLE INITIALLY DEFERRED,
    ADD CONSTRAINT fk_person_organization
        FOREIGN KEY (member_of_organization_id) REFERENCES organization (organization_id)
        DEFERRABLE INITIALLY DEFERRED;

ALTER TABLE organization
    ADD CONSTRAINT fk_organization_manager
        FOREIGN KEY (manager_person_id) REFERENCES person (person_id)
        DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE skill (
    skill_id    INTEGER      PRIMARY KEY,
    skill_name  VARCHAR(255) NOT NULL,
    status      VARCHAR(20)  NOT NULL CHECK (status IN ('APPROVED', 'CANCELED')),
    skill_type  VARCHAR(20)  NOT NULL CHECK (skill_type IN ('KNOWLEDGE', 'EXPERIENCE', 'TECHNOLOGY', 'OTHER'))
);

CREATE TABLE skill_proficiency_level (
    skill_proficiency_level_id    INTEGER      PRIMARY KEY,
    skill_proficiency_level_name  VARCHAR(255) NOT NULL
);

-- Skills Inventory: which skills each person has
CREATE TABLE person_skill (
    person_id  INTEGER     NOT NULL REFERENCES person (person_id),
    skill_id   INTEGER     NOT NULL REFERENCES skill (skill_id),
    status     VARCHAR(20) NOT NULL CHECK (status IN ('REQUESTED', 'APPROVED', 'CANCELED')),
    PRIMARY KEY (person_id, skill_id)
);

-- Matches com.group9.skillshub.projects.model.Project
CREATE TABLE projects (
    project_id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_name                    VARCHAR(255) NOT NULL,
    status                          VARCHAR(20)  NOT NULL CHECK (status IN ('APPROVED', 'CANCELED')),
    project_owning_organization_id  INTEGER      NOT NULL REFERENCES organization (organization_id),
    project_start_date              DATE         NOT NULL,
    project_end_date                DATE         NOT NULL,
    CHECK (project_end_date >= project_start_date)
);

-- Matches com.group9.skillshub.projects.model.ProjectSkillRequired
CREATE TABLE project_skill_required (
    project_id                  INTEGER     NOT NULL REFERENCES projects (project_id),
    skill_id                    INTEGER     NOT NULL REFERENCES skill (skill_id),
    skill_proficiency_level_id  INTEGER     NOT NULL REFERENCES skill_proficiency_level (skill_proficiency_level_id),
    status                      VARCHAR(20) NOT NULL CHECK (status IN ('APPROVED', 'CANCELED')),
    PRIMARY KEY (project_id, skill_id, skill_proficiency_level_id)
);

-- Matches com.group9.skillshub.projects.model.PersonProjectAssignment
CREATE TABLE person_project_assignment (
    person_id   INTEGER     NOT NULL REFERENCES person (person_id),
    project_id  INTEGER     NOT NULL REFERENCES projects (project_id),
    status      VARCHAR(20) NOT NULL CHECK (status IN ('REQUESTED', 'APPROVED', 'CANCELED')),
    PRIMARY KEY (person_id, project_id)
);

CREATE INDEX idx_person_manager      ON person (manager_person_id);
CREATE INDEX idx_person_organization ON person (member_of_organization_id);
CREATE INDEX idx_projects_org        ON projects (project_owning_organization_id);
CREATE INDEX idx_psr_skill           ON project_skill_required (skill_id);

